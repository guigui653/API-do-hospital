CREATE TABLE triagem
(
    id_triagem       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_paciente      BIGINT,
    nome_paciente    VARCHAR(255)                            NOT NULL,
    cpf              VARCHAR(255)                            NOT NULL,
    idade            INTEGER,
    pressao_arterial VARCHAR(255),
    temperatura      DOUBLE PRECISION,
    sintomas         VARCHAR(255)                            NOT NULL,
    urgencia         VARCHAR(255)                            NOT NULL,
    data_triagem     TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_triagem PRIMARY KEY (id_triagem)
);